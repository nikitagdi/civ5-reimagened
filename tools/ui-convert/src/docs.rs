//! The "Profile" section of `docs/ui-skins.md`, generated from the profile file (`cargo xtask ui docs`).
//!
//! The section sits between two marker comments; everything outside them is written by hand and kept as it is.
//! The text is a pure function of `profile.toml` (and of the shorthands the converter accepts), so a test can
//! check that the document is current: `cargo test -p ui2-convert docs_up_to_date`.

use std::fmt::Write as _;
use std::path::PathBuf;

use ui2_package::profile::{Profile, PropId, Tag, ValueKind};

use crate::check::SHORTHANDS;

/// The document, relative to the repository root.
pub const DOC_FILE: &str = "docs/ui-skins.md";
/// The profile file, relative to the repository root.
pub const PROFILE_FILE: &str = "crates/shared/ui2-package/profile/profile.toml";
/// The line before the generated section.
pub const BEGIN: &str = "<!-- profile: generated by `cargo xtask ui docs` from the profile file; edit profile.toml, not this section -->";
/// The line after it.
pub const END: &str = "<!-- profile: end -->";

const PROFILE_TEXT: &str = include_str!("../../../crates/shared/ui2-package/profile/profile.toml");

/// The document's path in this checkout.
pub fn doc_path() -> PathBuf {
    crate::fonts::repo_root().join(DOC_FILE)
}

/// `|` would end a table cell.
fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

/// Plain text in a table cell: `<name>` would read as an HTML tag.
fn text_cell(s: &str) -> String {
    cell(&s.replace('<', "&lt;").replace('>', "&gt;"))
}

fn code_list<S: AsRef<str>>(items: &[S]) -> String {
    items
        .iter()
        .map(|s| format!("`{}`", s.as_ref()))
        .collect::<Vec<_>>()
        .join(", ")
}

/// What a kind of value accepts, in words.
fn kind_text(kind: ValueKind) -> &'static str {
    match kind {
        ValueKind::Keyword => "one of",
        ValueKind::KeywordSet => "a set of keywords",
        ValueKind::Length => "a length",
        ValueKind::Color => "a color",
        ValueKind::Number => "a number",
        ValueKind::Integer => "an integer",
        ValueKind::Radius => "one or two lengths",
        ValueKind::Shadows => "a list of shadows",
        ValueKind::Transform => "translate, rotate and scale functions",
        ValueKind::Origin => "two lengths or side keywords",
        ValueKind::Times => "a list of times (s, ms)",
        ValueKind::Easings => "a list of timing functions",
        ValueKind::Properties => "`all`, `none` or animatable properties",
        ValueKind::Families => "a list of font families",
        ValueKind::LineHeight => "`normal`, a length or a number",
        ValueKind::Images => "a list of gradients and `url()` pictures",
        ValueKind::BgSizes => "a list of `auto`, `cover`, `contain` or sizes",
        ValueKind::Lengths => "a list of lengths",
        ValueKind::Repeats => "a list of repeat values",
        ValueKind::Keywords => "a list, each one of",
        ValueKind::Ratio => "`auto` or `w / h`",
        ValueKind::Tracks => "`none` or a track list",
        ValueKind::TrackSizes => "a list of track sizes",
        ValueKind::GridLine => "`auto`, a line number or `span N`",
        ValueKind::Url => "`url()` of a picture",
        ValueKind::Slice => "one to four numbers or percentages, and `fill`",
        ValueKind::ImageWidths => "one to four px lengths or numbers",
        ValueKind::ImageRepeat => "one or two of",
        ValueKind::Polygon => "`none` or a convex `polygon()`",
    }
}

fn num(v: f64) -> String {
    if v.fract() == 0.0 {
        format!("{}", v as i64)
    } else {
        format!("{v}")
    }
}

/// The values of a property, in words.
fn values_text(id: PropId) -> String {
    let d = Profile::v1().def(id);
    let mut s = match d.kind {
        ValueKind::Length if !d.pct => "a length in px".to_string(),
        k => kind_text(k).to_string(),
    };
    match d.kind {
        ValueKind::KeywordSet => {
            let (first, rest) = d
                .values
                .split_first()
                .map_or(("", &[][..]), |(f, r)| (f.as_str(), r));
            s = format!("`{first}`, or any of {} together", code_list(rest));
        }
        ValueKind::Keyword | ValueKind::Keywords | ValueKind::ImageRepeat => {
            s = format!("{s} {}", code_list(&d.values));
        }
        _ if !d.values.is_empty() => s = format!("{s}, or {}", code_list(&d.values)),
        _ => {}
    }
    match (d.min, d.max) {
        (Some(a), Some(b)) if a == b => {
            let _ = write!(s, "; only {}", num(a));
        }
        (Some(a), Some(b)) => {
            let _ = write!(s, "; {}..{}", num(a), num(b));
        }
        (Some(a), None) => {
            let _ = write!(s, "; at least {}", num(a));
        }
        (None, Some(b)) => {
            let _ = write!(s, "; at most {}", num(b));
        }
        (None, None) => {}
    }
    match d.max_items {
        Some(1) => s.push_str("; one item"),
        Some(n) => {
            let _ = write!(s, "; at most {n} items");
        }
        None => {}
    }
    if d.calc {
        s.push_str("; `calc()`");
    }
    s
}

fn flags_text(id: PropId) -> String {
    let d = Profile::v1().def(id);
    let mut f = Vec::new();
    if d.inherited {
        f.push("inherited");
    }
    if d.anim {
        f.push("transition");
    }
    if d.bind {
        f.push("bind");
    }
    if d.token {
        f.push("token");
    }
    f.join(", ")
}

/// The property groups of the file: the first sentence of the comment block above a run of `prop.` lines, and
/// the properties under it, in file order.
fn groups() -> Vec<(String, Vec<PropId>)> {
    let mut out: Vec<(String, Vec<PropId>)> = Vec::new();
    let mut comment: Option<String> = None;
    let mut open = false;
    for line in PROFILE_TEXT.lines() {
        let l = line.trim();
        if let Some(c) = l.strip_prefix("# ") {
            if comment.is_none() || open {
                let head = c.split([':', '.']).next().unwrap_or(c).trim();
                comment = Some(head.to_string());
                open = false;
            }
            continue;
        }
        let Some(rest) = l.strip_prefix("prop.") else {
            if !l.is_empty() {
                comment = None;
            }
            continue;
        };
        let name = rest.split([' ', '=']).next().unwrap_or("");
        let Some(id) = PropId::from_name(name) else {
            continue;
        };
        if !open {
            out.push((
                comment.clone().unwrap_or_else(|| "Properties".into()),
                Vec::new(),
            ));
            open = true;
        }
        if let Some(g) = out.last_mut() {
            g.1.push(id);
        }
    }
    out
}

/// The error codes of the file with their texts, in code order.
fn error_rows() -> Vec<(String, String, String)> {
    let t: toml::Table = PROFILE_TEXT.parse().unwrap_or_default();
    let mut out: Vec<(String, String, String)> = t
        .get("error")
        .and_then(toml::Value::as_table)
        .map(|errs| {
            errs.iter()
                .map(|(code, v)| {
                    let s = |k: &str| {
                        v.get(k)
                            .and_then(toml::Value::as_str)
                            .unwrap_or("")
                            .to_string()
                    };
                    (code.clone(), s("what"), s("hint"))
                })
                .collect()
        })
        .unwrap_or_default();
    out.sort();
    out
}

/// The generated section, markers included, with a line end after the end marker.
pub fn profile_section() -> String {
    let p = Profile::v1();
    let (major, minor) = p.version();
    let mut s = String::new();
    s.push_str(BEGIN);
    s.push('\n');
    let _ = writeln!(s, "## Profile {major}.{minor}\n");
    let _ = writeln!(
        s,
        "What a skin may use. This section is generated from the profile file `{PROFILE_FILE}`, which the converter \
         reads; a change to the profile is a change to that file, and `cargo xtask ui docs` writes this section again.\n"
    );

    // Elements.
    s.push_str("### Elements\n\n| Group | Elements |\n|---|---|\n");
    let mut by_group: Vec<(String, Vec<String>)> = Vec::new();
    for &tag in Tag::ALL {
        let Some(def) = p.element(tag) else { continue };
        let mut name = format!("`{}`", tag.name());
        let mut notes = Vec::new();
        if !def.types.is_empty() {
            notes.push(format!("type {}", code_list(&def.types)));
        }
        for (k, v) in &def.require {
            notes.push(format!("`{k}: {v}`"));
        }
        if !notes.is_empty() {
            name = format!("{name} ({})", notes.join("; "));
        }
        match by_group.iter_mut().find(|(g, _)| *g == def.group) {
            Some((_, list)) => list.push(name),
            None => by_group.push((def.group.clone(), vec![name])),
        }
    }
    for (group, list) in &by_group {
        let _ = writeln!(s, "| {group} | {} |", cell(&list.join(", ")));
    }
    s.push_str(
        "\nThe notes in parentheses are what the element must have: the allowed `type`, and computed values the skin \
         sets itself (the browser's own look of controls and lists is not part of the profile).\n\n",
    );

    // Properties.
    s.push_str(
        "### Properties\n\nLonghands only: Chrome bakes the shorthands of the list below into them. A property outside \
         the table with a value other than its initial one is an error, wherever the value came from. Flags: \
         *inherited*; *transition* (can be animated by `transition`); *bind* (can be set by \
         `data-bind-style-<property>`); *token* (a color that may refer to a `:root` color token).\n\n",
    );
    for (group, ids) in groups() {
        let _ = writeln!(
            s,
            "#### {group}\n\n| Property | Values | Initial | Flags |\n|---|---|---|---|"
        );
        for id in ids {
            let d = p.def(id);
            let _ = writeln!(
                s,
                "| `{}` | {} | `{}` | {} |",
                id.name(),
                cell(&values_text(id)),
                cell(&d.initial),
                flags_text(id)
            );
        }
        s.push('\n');
    }
    let shorthands: Vec<&str> = SHORTHANDS.iter().map(|(n, _)| *n).collect();
    let _ = writeln!(
        s,
        "Shorthands a stylesheet may write: {}.\n",
        code_list(&shorthands)
    );

    // Ignored.
    s.push_str(
        "### Ignored properties\n\nAccepted and without effect.\n\n| Property | Why |\n|---|---|\n",
    );
    for (name, def) in p.ignored_props() {
        let _ = writeln!(s, "| `{name}` | {} |", text_cell(&def.why));
    }
    s.push('\n');

    // Selectors, slots, tokens.
    let sel = p.selector();
    let pseudo: Vec<String> = sel.pseudo_class.iter().map(|c| format!(":{c}")).collect();
    let comb: Vec<String> = sel
        .combinators
        .iter()
        .map(|c| {
            if c == " " {
                "a space".to_string()
            } else {
                format!("`{c}`")
            }
        })
        .collect();
    let _ = writeln!(
        s,
        "### Selectors\n\nTags, classes, ids and `:root`, joined by {}; the dynamic pseudo-classes {}. \
         `@media` takes width and height in px; the only other at-rule is `@font-face`.\n",
        comb.join(" or "),
        code_list(&pseudo)
    );
    let required_slots: Vec<&String> = p
        .slots()
        .iter()
        .filter(|(_, d)| d.required)
        .map(|(n, _)| n)
        .collect();
    let _ = writeln!(
        s,
        "### Extension points and color synonyms\n\nEvery skin has the extension points {} (`data-slot`) and defines \
         on `:root` the color synonyms mods read, each as `var(--<root token>)`:\n",
        code_list(&required_slots)
    );
    let tokens: Vec<&String> = p
        .tokens()
        .iter()
        .filter(|(_, d)| d.required)
        .map(|(n, _)| n)
        .collect();
    let _ = writeln!(s, "{}.\n", code_list(&tokens));

    // Errors.
    s.push_str(
        "### Error codes\n\nEvery code the converter and the profile's parsers report, with the text it prints.\n\n\
         | Code | What | Hint |\n|---|---|---|\n",
    );
    for (code, what, hint) in error_rows() {
        let _ = writeln!(
            s,
            "| {code} | {} | {} |",
            text_cell(&what),
            text_cell(&hint)
        );
    }
    s.push('\n');
    s.push_str(END);
    s.push('\n');
    s
}

/// The document with its profile section replaced by the current one (appended when the document has none).
pub fn update(doc: &str) -> String {
    let section = profile_section();
    let doc = doc.replace("\r\n", "\n");
    match (doc.find(BEGIN), doc.find(END)) {
        (Some(a), Some(b)) if b > a => {
            let after = doc[b + END.len()..]
                .strip_prefix('\n')
                .unwrap_or(&doc[b + END.len()..]);
            format!("{}{section}{after}", &doc[..a])
        }
        _ => {
            let mut out = doc.trim_end().to_string();
            out.push_str("\n\n");
            out.push_str(&section);
            out
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The profile section of `docs/ui-skins.md` is the one the profile file gives (`cargo xtask ui docs`).
    #[test]
    fn docs_up_to_date() {
        let doc = std::fs::read_to_string(doc_path()).expect("docs/ui-skins.md");
        let doc = doc.replace("\r\n", "\n");
        assert!(
            doc == update(&doc),
            "the profile section of {DOC_FILE} is stale: run `cargo xtask ui docs`"
        );
        let section = profile_section();
        assert!(doc.contains(&section));
        // No machine paths, only paths of the repository.
        for bad in [":\\", ":/", "/Users/", "/home/"] {
            assert!(!section.contains(bad), "{bad}");
        }
    }

    #[test]
    fn the_section_covers_the_profile() {
        let s = profile_section();
        assert!(s.starts_with(BEGIN) && s.ends_with(&format!("{END}\n")));
        assert!(s.contains("## Profile 1.0\n"));
        for &id in PropId::ALL {
            assert!(s.contains(&format!("| `{}` |", id.name())), "{}", id.name());
        }
        for &tag in Tag::ALL {
            assert!(s.contains(&format!("`{}`", tag.name())), "{}", tag.name());
        }
        for code in crate::errors::codes::ALL {
            assert!(s.contains(&format!("| {code} |")), "{code}");
        }
        assert!(s.contains("`--ui-text`"));
        assert!(s.contains("#### Layout\n"));
    }

    #[test]
    fn update_replaces_only_the_section() {
        let a = format!("# T\n\nhand\n\n{BEGIN}\nstale section\n{END}\n\nmore\n");
        let b = update(&a);
        assert!(b.starts_with("# T\n\nhand\n\n"));
        assert!(b.ends_with(&format!("{END}\n\nmore\n")));
        assert!(!b.contains("stale section"));
        assert_eq!(update(&b), b);
        let c = update("# T\n");
        assert!(c.starts_with("# T\n\n") && c.ends_with(&format!("{END}\n")));
    }
}
