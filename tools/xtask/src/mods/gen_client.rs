//! Text of the generated client packages of `target/dist/client/`: `dist-client-web` (the wasm module) and
//! `dist-desktop` (the native client). Both register the client half of each mod in a `ClientRegistry`, one
//! `register_<id>` function per mod, and hand the hook over to the public app entry (`app_web::start_with`,
//! `app_desktop::main_with`).

use std::path::Path;

use super::dist::{DistMod, toml_path};

fn q(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

fn path_dep(name: &str, dir: &Path) -> String {
    format!("{} = {{ path = {} }}\n", q(name), q(&toml_path(dir)))
}

/// `[dependencies]` shared by both packages: the public crates the generated code names, and the client halves.
fn common_deps(root: &Path, mod_crates: &[(&str, &Path)]) -> String {
    let mut s = String::new();
    s.push_str(&path_dep(
        "client-app",
        &root.join("crates/client/client-app"),
    ));
    s.push_str(&path_dep(
        "mod-client",
        &root.join("crates/client/mod-client"),
    ));
    s.push_str(&path_dep("mod-api", &root.join("crates/shared/mod-api")));
    for (name, dir) in mod_crates {
        s.push_str(&path_dep(name, dir));
    }
    s
}

/// `dist-client-web`: a cdylib named `app_web` (so the page and the bindgen step are the public ones) over the
/// public `app-web` with its own start function.
pub fn web_manifest(root: &Path, mod_crates: &[(&str, &Path)], wasm_bindgen: &str) -> String {
    let mut s = String::from(
        "# Generated by `cargo xtask mods build --target client`. Do not edit.\n\
         [package]\n\
         name = \"dist-client-web\"\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         license = \"AGPL-3.0-or-later\"\n\n\
         [package.metadata.civ5]\n\
         layer = \"app-web\"\n\n\
         [lib]\n\
         name = \"app_web\"\n\
         path = \"src/lib.rs\"\n\
         crate-type = [\"cdylib\"]\n\n\
         [dependencies]\n",
    );
    s.push_str(&format!(
        "app-web = {{ path = {}, features = [\"external-start\"] }}\n",
        q(&toml_path(&root.join("apps/web")))
    ));
    s.push_str(&format!("wasm-bindgen = {}\n", q(wasm_bindgen)));
    s.push_str(&common_deps(root, mod_crates));
    s
}

/// `dist-desktop`: the public client under its public name, with the hooks of the mods.
pub fn desktop_manifest(root: &Path, mod_crates: &[(&str, &Path)]) -> String {
    let mut s = String::from(
        "# Generated by `cargo xtask mods build --target client`. Do not edit.\n\
         [package]\n\
         name = \"dist-desktop\"\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         license = \"AGPL-3.0-or-later\"\n\n\
         [package.metadata.civ5]\n\
         layer = \"app-desktop\"\n\n\
         [[bin]]\n\
         name = \"app-desktop\"\n\
         path = \"src/main.rs\"\n\n\
         [dependencies]\n",
    );
    s.push_str(&path_dep("app-desktop", &root.join("apps/desktop")));
    s.push_str(&common_deps(root, mod_crates));
    s
}

/// A Rust identifier from a mod id (`-` is not allowed in one).
fn ident(id: &str) -> String {
    id.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// The first 16 bytes of the content hash of the mod, the code identity of the build (sent in `ModHello`).
pub fn code_hash(m: &DistMod) -> [u8; 16] {
    let mut out = [0u8; 16];
    out.copy_from_slice(&m.content_hash[..16]);
    out
}

/// `mod_hooks()` and one `register_<id>` per mod with a client half. A mod without one registers nothing.
pub fn hooks_rs(mods: &[DistMod]) -> String {
    let with_code: Vec<(&DistMod, &super::dist::CrateRef)> = mods
        .iter()
        .filter_map(|m| m.client.as_ref().map(|c| (m, c)))
        .collect();
    let mut s = String::new();
    s.push_str("/// The hooks of the client halves of the mods, registered in load order.\n");
    s.push_str("fn mod_hooks() -> client_app::mod_hooks::ModHooks {\n");
    if with_code.is_empty() {
        s.push_str("    client_app::mod_hooks::ModHooks::new()\n}\n");
        return s;
    }
    s.push_str("    let mut registry = mod_client::ClientRegistry::new();\n");
    for (m, _) in &with_code {
        s.push_str(&format!("    register_{}(&mut registry);\n", ident(&m.id)));
    }
    s.push_str(
        "    assert!(\n        registry.problems().is_empty(),\n        \"client mods: {:?}\",\n        registry.problems()\n    );\n",
    );
    s.push_str(
        "    let mut hooks = client_app::mod_hooks::ModHooks::new();\n    \
         if let Some(hook) = client_app::mod_net::ClientModsHook::new(registry) {\n        \
         hooks.register(Box::new(hook));\n    }\n    hooks\n}\n",
    );
    for (m, c) in &with_code {
        let caps: Vec<String> = m.caps.iter().map(|c| format!("{c:?}")).collect();
        let hash: Vec<String> = code_hash(m).iter().map(|b| format!("0x{b:02x}")).collect();
        s.push_str(&format!(
            "\n/// {id} {version}\nfn register_{ident}(r: &mut mod_client::ClientRegistry) {{\n    \
             {entry}(r);\n    \
             r.set_build(\n        {idq:?},\n        mod_client::ModBuild {{\n            \
             version: mod_api::Version::new({ma}, {mi}, {pa}),\n            \
             caps: mod_api::Caps::from_names([{caps}]).expect(\"capabilities of mod.toml\"),\n            \
             code_hash: [{hash}],\n        }},\n    );\n}}\n",
            id = m.id,
            version = m.version,
            ident = ident(&m.id),
            entry = c.entry,
            idq = m.id,
            ma = m.version_parts.0,
            mi = m.version_parts.1,
            pa = m.version_parts.2,
            caps = caps.join(", "),
            hash = hash.join(", "),
        ));
    }
    s
}

fn header(mods: &[DistMod], what: &str) -> String {
    let mut s = format!(
        "//! Generated by `cargo xtask mods build --target client`. Do not edit.\n\
         //!\n\
         //! {what} with the client halves of these mods linked in:\n"
    );
    for m in mods {
        let note = if m.client.is_some() {
            ""
        } else {
            " (no client code)"
        };
        s.push_str(&format!("//! - {} {}{note}\n", m.id, m.version));
    }
    s.push('\n');
    s
}

/// `src/lib.rs` of `dist-client-web`: the module start function.
pub fn web_lib_rs(mods: &[DistMod]) -> String {
    let mut s = header(mods, "The public web client");
    s.push_str("#![cfg(target_arch = \"wasm32\")]\n\n");
    s.push_str(
        "use wasm_bindgen::prelude::*;\n\n\
         #[wasm_bindgen(start)]\npub fn start() {\n    app_web::start_with(mod_hooks());\n}\n\n",
    );
    s.push_str(&hooks_rs(mods));
    s
}

/// `src/main.rs` of `dist-desktop`.
pub fn desktop_main_rs(mods: &[DistMod]) -> String {
    let mut s = header(mods, "The public native client");
    s.push_str(
        "fn main() -> std::process::ExitCode {\n    \
         match app_desktop::main_with(mod_hooks()) {\n        \
         Ok(()) => std::process::ExitCode::SUCCESS,\n        \
         Err(e) => {\n            eprintln!(\"Error: {e:?}\");\n            std::process::ExitCode::FAILURE\n        }\n    }\n}\n\n",
    );
    s.push_str(&hooks_rs(mods));
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mods::dist::CrateRef;
    use std::path::PathBuf;

    fn m(id: &str, client: Option<(&str, &str)>) -> DistMod {
        DistMod {
            id: id.into(),
            version: "1.2.3".into(),
            version_parts: (1, 2, 3),
            dir: PathBuf::from("/m").join(id),
            server: None,
            client: client.map(|(n, e)| CrateRef {
                name: n.into(),
                dir: PathBuf::from("/m").join(id).join(n),
                entry: e.into(),
            }),
            caps: vec!["net.channel".into(), "camera".into()],
            content_hash: {
                let mut h = [0u8; 32];
                h[0] = 0xab;
                h[15] = 0xcd;
                h[16] = 0xff;
                h
            },
        }
    }

    #[test]
    fn one_register_function_per_mod_in_load_order() {
        let s = hooks_rs(&[
            m("aa", Some(("aa-client", "aa_client::register"))),
            m("bb", None),
            m("c-c", Some(("cc-client", "cc_client::setup"))),
        ]);
        let a = s.find("register_aa(&mut registry);").unwrap();
        let c = s.find("register_c_c(&mut registry);").unwrap();
        assert!(a < c);
        assert!(s.contains("fn register_aa(r: &mut mod_client::ClientRegistry)"));
        assert!(s.contains("aa_client::register(r);"));
        assert!(s.contains("cc_client::setup(r);"));
        assert!(!s.contains("register_bb"));
        assert_eq!(s.matches("set_build(").count(), 2);
        assert!(s.contains("mod_api::Version::new(1, 2, 3)"));
        assert!(s.contains("from_names([\"net.channel\", \"camera\"])"));
        assert!(s.contains("0xab, 0x00"));
        // 16 bytes: the byte 16 (0xff) is not in the hash.
        assert!(s.contains("0xcd]"));
        assert!(!s.contains("0xff"));
    }

    #[test]
    fn no_client_code_is_the_public_client() {
        let s = hooks_rs(&[m("bb", None)]);
        assert!(s.contains("client_app::mod_hooks::ModHooks::new()"));
        assert!(!s.contains("ClientRegistry"));
        let main = desktop_main_rs(&[m("bb", None)]);
        assert!(main.contains("//! - bb 1.2.3 (no client code)"));
        assert!(main.contains("app_desktop::main_with(mod_hooks())"));
    }

    #[test]
    fn web_start_calls_the_public_entry() {
        let s = web_lib_rs(&[m("aa", Some(("aa-client", "aa_client::register")))]);
        assert!(s.contains("#[wasm_bindgen(start)]"));
        assert!(s.contains("app_web::start_with(mod_hooks());"));
    }

    #[test]
    fn manifests_use_path_dependencies_and_the_public_names() {
        let root = PathBuf::from("/repo");
        let dir = PathBuf::from("/m/aa/aa-client");
        let w: toml::Table = web_manifest(&root, &[("aa-client", dir.as_path())], "=0.2.129")
            .parse()
            .unwrap();
        assert_eq!(w["lib"]["name"].as_str(), Some("app_web"));
        assert_eq!(w["lib"]["crate-type"][0].as_str(), Some("cdylib"));
        let deps = w["dependencies"].as_table().unwrap();
        assert_eq!(deps["wasm-bindgen"].as_str(), Some("=0.2.129"));
        assert_eq!(
            deps["app-web"]["features"][0].as_str(),
            Some("external-start")
        );
        assert_eq!(deps["aa-client"]["path"].as_str(), Some("/m/aa/aa-client"));
        let d: toml::Table = desktop_manifest(&root, &[("aa-client", dir.as_path())])
            .parse()
            .unwrap();
        assert_eq!(d["bin"][0]["name"].as_str(), Some("app-desktop"));
        assert_eq!(
            d["dependencies"]["app-desktop"]["path"].as_str(),
            Some("/repo/apps/desktop")
        );
    }
}
