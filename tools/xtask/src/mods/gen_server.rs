//! Text of the generated server package of `target/dist/`.

use std::path::Path;

use super::dist::{DistMod, toml_path};

fn q(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

fn path_dep(name: &str, dir: &Path) -> String {
    format!("{} = {{ path = {} }}\n", q(name), q(&toml_path(dir)))
}

/// `dist-server`: the public server crate and the server halves of the mods, by path. The bin keeps the public
/// name `civ5-server` (the supervisor starts its own executable as the worker, scripts look for that name).
pub fn server_manifest(root: &Path, mod_crates: &[(&str, &Path)]) -> String {
    let mut s = String::from(
        "# Generated by `cargo xtask mods build`. Do not edit.\n\
         [package]\n\
         name = \"dist-server\"\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         license = \"AGPL-3.0-or-later\"\n\n\
         [package.metadata.civ5]\n\
         layer = \"server\"\n\n\
         [[bin]]\n\
         name = \"civ5-server\"\n\
         path = \"src/main.rs\"\n\n\
         [dependencies]\n",
    );
    s.push_str(&path_dep("server", &root.join("crates/server/server")));
    s.push_str(&path_dep(
        "mod-host-server",
        &root.join("crates/server/mod-host-server"),
    ));
    for (name, dir) in mod_crates {
        s.push_str(&path_dep(name, dir));
    }
    s
}

/// `graph` (mods check): depends on every Rust half, so the metadata graph holds them all. Not built.
pub fn graph_manifest(crates: &[(&str, &Path)]) -> String {
    let mut s = String::from(
        "# Generated by `cargo xtask mods check`. Do not edit.\n\
         [package]\n\
         name = \"dist-graph\"\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\n\
         [package.metadata.civ5]\n\
         layer = \"tool\"\n\n\
         [dependencies]\n",
    );
    for (name, dir) in crates {
        s.push_str(&path_dep(name, dir));
    }
    s
}

/// The `main.rs` of the dist server: the public server entry with a registry that holds the server half of each
/// mod, in load order.
pub fn main_rs(mods: &[DistMod]) -> String {
    let mut s = String::from(
        "//! Generated by `cargo xtask mods build`. Do not edit.\n\
         //!\n\
         //! The public server with the server halves of these mods linked in:\n",
    );
    let with_code: Vec<&DistMod> = mods.iter().filter(|m| m.server.is_some()).collect();
    for m in mods {
        let note = if m.server.is_some() {
            ""
        } else {
            " (no server code)"
        };
        s.push_str(&format!("//! - {} {}{note}\n", m.id, m.version));
    }
    s.push_str("\nfn main() -> std::process::ExitCode {\n");
    if with_code.is_empty() {
        s.push_str("    let registry = mod_host_server::HostRegistry::new();\n");
    } else {
        s.push_str("    let mut registry = mod_host_server::HostRegistry::new();\n    registry\n");
        for m in &with_code {
            if let Some(c) = &m.server {
                s.push_str(&format!("        .register({})\n", c.entry));
            }
        }
        s.push_str("    ;\n");
    }
    s.push_str("    server::entry::main_with(registry)\n}\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mods::dist::CrateRef;
    use std::path::PathBuf;

    fn m(id: &str, server: Option<(&str, &str)>) -> DistMod {
        DistMod {
            id: id.into(),
            version: "0.1.0".into(),
            version_parts: (0, 1, 0),
            dir: PathBuf::from("/m").join(id),
            server: server.map(|(n, e)| CrateRef {
                name: n.into(),
                dir: PathBuf::from("/m").join(id).join(n),
                entry: e.into(),
            }),
            client: None,
            caps: Vec::new(),
            content_hash: [0; 32],
        }
    }

    #[test]
    fn main_registers_the_server_halves_in_load_order() {
        let s = main_rs(&[
            m("aa", Some(("aa-server", "aa_server::register"))),
            m("bb", None),
            m("cc", Some(("cc-server", "cc_server::setup"))),
        ]);
        let a = s.find(".register(aa_server::register)").unwrap();
        let c = s.find(".register(cc_server::setup)").unwrap();
        assert!(a < c);
        assert!(s.contains("//! - bb 0.1.0 (no server code)"));
        assert!(s.contains("server::entry::main_with(registry)"));
        assert!(!s.contains("bb_"));
    }

    #[test]
    fn main_without_server_code_is_the_public_server() {
        let s = main_rs(&[m("bb", None)]);
        assert!(s.contains("let registry = mod_host_server::HostRegistry::new();"));
        assert!(!s.contains(".register("));
    }

    #[test]
    fn manifest_uses_path_dependencies_only() {
        let root = PathBuf::from("/repo");
        let dir = PathBuf::from("/m/aa/aa-server");
        let s = server_manifest(&root, &[("aa-server", dir.as_path())]);
        let t: toml::Table = s.parse().unwrap();
        let deps = t["dependencies"].as_table().unwrap();
        assert_eq!(deps.len(), 3);
        for (_, v) in deps {
            assert!(v.get("path").is_some(), "{v}");
        }
        assert_eq!(
            deps["server"]["path"].as_str(),
            Some("/repo/crates/server/server")
        );
        assert_eq!(
            t["package"]["metadata"]["civ5"]["layer"].as_str(),
            Some("server")
        );
        assert_eq!(t["bin"][0]["name"].as_str(), Some("civ5-server"));
        assert!(!s.contains("[patch"));
    }
}
