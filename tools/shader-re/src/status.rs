//! `status.toml`: port status of every world entry (in git; porters edit it).
//!
//! ```toml
//! [entry."UnitShader::UnitPS:PS"]
//! status = "todo"        # todo | ported | ported-dx11 | not-needed
//! ```

use std::collections::BTreeMap;
use std::path::Path;

use serde::{Deserialize, Serialize};

#[derive(Debug, thiserror::Error)]
pub enum StatusError {
    #[error("{path}: {source}", path = .path.display())]
    Io {
        path: std::path::PathBuf,
        source: std::io::Error,
    },
    #[error("status.toml: {0}")]
    Parse(String),
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Status {
    #[default]
    #[serde(rename = "todo")]
    Todo,
    #[serde(rename = "ported")]
    Ported,
    #[serde(rename = "ported-dx11")]
    PortedDx11,
    #[serde(rename = "not-needed")]
    NotNeeded,
}

impl Status {
    pub fn name(self) -> &'static str {
        match self {
            Status::Todo => "todo",
            Status::Ported => "ported",
            Status::PortedDx11 => "ported-dx11",
            Status::NotNeeded => "not-needed",
        }
    }
}

/// A constant of the original that our shader takes from another source.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct DataMove {
    pub ctab: String,
    pub to: String,
}

/// An input (`v<N>`) whose random values stay in `min..=max` in the comparison: for inputs the
/// original only ever feeds from a narrow range (indices into a constant array).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct InputRange {
    pub input: String,
    pub min: i32,
    pub max: i32,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct StatusEntry {
    #[serde(default)]
    pub status: Status,
    /// sha1 of the SM3 block the port was made from.
    #[serde(default)]
    pub sha1: Option<String>,
    /// `crates/client/render/src/shaders/unit/unit.wgsl#unit_ps`.
    #[serde(default)]
    pub wgsl: Option<String>,
    /// Files (from the repo root) that go before `wgsl`, as `wgsl_module!` joins them: the shared
    /// parts a module needs (`frame.wgsl`, `sm3.wgsl`). `compare` and `check` use the joined text.
    #[serde(default)]
    pub modules: Vec<String>,
    #[serde(default)]
    pub owner: Option<String>,
    #[serde(default)]
    pub zero_in_compare: Vec<String>,
    #[serde(default)]
    pub data_moves: Vec<DataMove>,
    /// Inputs limited to a range in the comparison, e.g. `{ input = "v4", min = 0, max = 95 }`.
    #[serde(default)]
    pub input_ranges: Vec<InputRange>,
    /// Required for `not-needed`.
    #[serde(default)]
    pub reason: Option<String>,
    /// Replay test of a `ported-dx11` entry (`golden`, AC-R9.6).
    #[serde(default)]
    pub replay: Option<String>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct StatusFile {
    #[serde(default)]
    pub entry: BTreeMap<String, StatusEntry>,
}

impl StatusFile {
    pub fn parse(text: &str) -> Result<StatusFile, StatusError> {
        toml::from_str(text).map_err(|e| StatusError::Parse(e.to_string()))
    }

    pub fn load(path: &Path) -> Result<StatusFile, StatusError> {
        let text = std::fs::read_to_string(path).map_err(|source| StatusError::Io {
            path: path.to_path_buf(),
            source,
        })?;
        StatusFile::parse(&text)
    }

    /// Status of `name`; entries the file does not list are `todo`.
    pub fn status_of(&self, name: &str) -> Status {
        self.entry.get(name).map_or(Status::Todo, |e| e.status)
    }
}

/// The text of a fresh `status.toml`: every name `todo`, sorted. Existing entries of `keep` stay
/// as they are, so that regenerating does not lose what porters wrote.
pub fn render(names: &[String], keep: &StatusFile) -> String {
    let mut out = String::from(
        "# Port status of every world shader entry. In git; porters edit it.\n\
         # status: todo | ported | ported-dx11 | not-needed (reason required)\n\
         # Regenerated by `shader-re status-init`: new names are added as todo, existing ones are kept.\n",
    );
    let mut sorted: Vec<&String> = names.iter().collect();
    sorted.sort();
    sorted.dedup();
    for name in sorted {
        out.push('\n');
        out.push_str(&format!("[entry.\"{name}\"]\n"));
        match keep.entry.get(name.as_str()) {
            None => out.push_str("status = \"todo\"\n"),
            Some(e) => out.push_str(&render_entry(e)),
        }
    }
    out
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

fn render_entry(e: &StatusEntry) -> String {
    let mut s = format!("status = \"{}\"\n", e.status.name());
    for (k, v) in [
        ("sha1", &e.sha1),
        ("wgsl", &e.wgsl),
        ("owner", &e.owner),
        ("reason", &e.reason),
        ("replay", &e.replay),
    ] {
        if let Some(v) = v {
            s.push_str(&format!("{k} = {}\n", quote(v)));
        }
    }
    if !e.zero_in_compare.is_empty() {
        let v: Vec<String> = e.zero_in_compare.iter().map(|x| quote(x)).collect();
        s.push_str(&format!("zero_in_compare = [{}]\n", v.join(", ")));
    }
    if !e.data_moves.is_empty() {
        let v: Vec<String> = e
            .data_moves
            .iter()
            .map(|m| format!("{{ ctab = {}, to = {} }}", quote(&m.ctab), quote(&m.to)))
            .collect();
        s.push_str(&format!("data_moves = [{}]\n", v.join(", ")));
    }
    if !e.input_ranges.is_empty() {
        let v: Vec<String> = e
            .input_ranges
            .iter()
            .map(|r| {
                format!(
                    "{{ input = {}, min = {}, max = {} }}",
                    quote(&r.input),
                    r.min,
                    r.max
                )
            })
            .collect();
        s.push_str(&format!("input_ranges = [{}]\n", v.join(", ")));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_the_documented_shape() {
        let f = StatusFile::parse(
            r#"
[entry."UnitShader::UnitPS:PS"]
status = "ported"
sha1 = "3f2a"
wgsl = "a.wgsl#unit_ps"
owner = "render-core"
zero_in_compare = ["g_vHalfPixel"]
data_moves = [{ ctab = "g_mWorld", to = "instance:world" }]

[entry."X::Y:VS"]
status = "not-needed"
reason = "unused"
"#,
        )
        .unwrap();
        assert_eq!(f.status_of("UnitShader::UnitPS:PS"), Status::Ported);
        assert_eq!(f.status_of("X::Y:VS"), Status::NotNeeded);
        assert_eq!(f.status_of("Z::Q:PS"), Status::Todo);
        let e = &f.entry["UnitShader::UnitPS:PS"];
        assert_eq!(e.data_moves[0].to, "instance:world");
        assert_eq!(e.zero_in_compare, ["g_vHalfPixel"]);
    }

    #[test]
    fn input_ranges_parse_and_render_back() {
        let text = "[entry.\"A::b:VS\"]\nstatus = \"ported\"\n\
                    input_ranges = [{ input = \"v4\", min = 0, max = 95 }]\n";
        let f = StatusFile::parse(text).unwrap();
        let e = &f.entry["A::b:VS"];
        assert_eq!(e.input_ranges.len(), 1);
        assert_eq!((e.input_ranges[0].min, e.input_ranges[0].max), (0, 95));
        let back = StatusFile::parse(&render(&["A::b:VS".to_string()], &f)).unwrap();
        assert_eq!(back, f);
    }

    #[test]
    fn unknown_keys_and_statuses_are_errors() {
        assert!(StatusFile::parse("[entry.\"A::B:PS\"]\nstatus = \"maybe\"\n").is_err());
        assert!(StatusFile::parse("[entry.\"A::B:PS\"]\nstatuss = \"todo\"\n").is_err());
        assert!(StatusFile::parse("[other]\n").is_err());
    }

    #[test]
    fn render_round_trips_and_keeps_existing_entries() {
        let kept = StatusFile::parse(
            "[entry.\"B::b:PS\"]\nstatus = \"ported\"\nsha1 = \"ab\"\nwgsl = \"x.wgsl#f\"\n\
             data_moves = [{ ctab = \"m\", to = \"instance:world\" }]\n",
        )
        .unwrap();
        let names = vec!["B::b:PS".to_string(), "A::a:VS".to_string()];
        let text = render(&names, &kept);
        let back = StatusFile::parse(&text).unwrap();
        assert_eq!(back.entry["B::b:PS"], kept.entry["B::b:PS"]);
        assert_eq!(back.status_of("A::a:VS"), Status::Todo);
        assert!(text.find("A::a:VS").unwrap() < text.find("B::b:PS").unwrap());
        // Rendering again changes nothing.
        assert_eq!(render(&names, &back), text);
    }
}
