//! The unit blend graphs (`.dge`, Granny DAG2 files of `Resource/Common/UnitModels.fpk`) as one text
//! table, one expression per graph: the format `render::anim::dge` parses (blob
//! `asset_format::DGE_GRAPHS_ID`, written by the set `client-data`).
//!
//! A `.dge` is a plain Granny file whose root is `{ DAGs[], ExtendedData }`; every graph of the
//! install has one DAG `{ RootNodeIndex, Sources[] {EventCode}, TrackMasks[] {BindingName}, Nodes[] }`.
//! A node has named input edges (`InputNodeIndex`, -1 when unconnected) and a typed `NodeData`
//! (`TypeMarker_NodeData<Kind>` is its first member). The expression starts at the root node
//! (a `Subgraph` that passes its pose input through) and writes:
//!
//! | node | text |
//! |---|---|
//! | PoseAnimSource | `ec<code>(loop=<LoopCount>,clamp=<ClampedLoop>,cont=<ContinueOffset>,spd=<Speed>,off=<Offset>)`, then ` IN[<scalar>]` for a connected input |
//! | Selection | `Select(sel=<scalar>, default=<DefaultEdge>){0:<pose>; 1:<pose>...}` |
//! | Blend | `Blend(p=<scalar>, from=<pose>, to=<pose>, mask=<Mask(<binding> w=<default>-><target>)>)` |
//! | ScalarSource | `const[<value>]` |
//! | BlockCurve (first block type 3, the S-curve) | `Curve3(<scalar>)` |
//! | ScalarCallback 5 / 6 / 7 | `BlendTime(<s>)` / `BlendEC(<code>)` / `Path(<index>)` |
//!
//! An unconnected input is `-`. Numbers are printed like C's `%g`. A graph with any other node or
//! callback is reported and left out of the table.

use std::collections::BTreeMap;

use granny::{GrannyFile, Object, Value};

/// Header of the table (comment lines start with `#`).
pub const TABLE_HEADER: &str = "# Unit blend graphs (.dge of Resource/Common/UnitModels.fpk), generated by civ5-assets from the\n# user's install: a line with the graph name, then its expression. loop=0 loops, loop=1 plays once\n# and holds; cont=1 keeps the phase.\n";

/// Name of the pack the unit graphs are read from.
pub const UNIT_GRAPH_PACK: &str = "unitmodels.fpk";

/// Like C's `printf("%g", v)`: 6 significant digits, trailing zeros dropped, exponent form below
/// 1e-4 and from 1e6.
pub fn fmt_g(v: f64) -> String {
    if v == 0.0 {
        return "0".into();
    }
    if !v.is_finite() {
        return format!("{v}");
    }
    let exp = v.abs().log10().floor() as i32;
    // Rounding to 6 digits can carry into the next power of ten.
    let rounded: f64 = format!("{v:.5e}").parse().unwrap_or(v);
    let exp = if rounded.abs() >= 10f64.powi(exp + 1) {
        exp + 1
    } else {
        exp
    };
    let strip = |s: String| -> String {
        if s.contains('.') {
            s.trim_end_matches('0').trim_end_matches('.').to_owned()
        } else {
            s
        }
    };
    if !(-4..6).contains(&exp) {
        let s = format!("{v:.5e}");
        let (mant, e) = s.split_once('e').unwrap_or((&s, "0"));
        let e: i32 = e.parse().unwrap_or(0);
        let sign = if e < 0 { '-' } else { '+' };
        format!("{}e{sign}{:02}", strip(mant.to_owned()), e.abs())
    } else {
        let decimals = (5 - exp).max(0) as usize;
        strip(format!("{v:.decimals$}"))
    }
}

/// `%g`, with `.0` added to a whole number (how the constants of the table are written).
fn fmt_const(v: f64) -> String {
    let s = fmt_g(v);
    if s.contains(['.', 'e', 'n', 'i']) {
        s
    } else {
        format!("{s}.0")
    }
}

type R<T> = Result<T, String>;

fn gerr(e: granny::GrannyError) -> String {
    e.to_string()
}

/// Elements of an array member, plain or of references.
fn items<'f>(o: &Object<'f>, name: &str) -> R<Vec<Object<'f>>> {
    match o.get(name).map_err(gerr)? {
        Value::Array(a) => Ok(a.resolve().map_err(gerr)?.iter().collect()),
        Value::ArrayOfReferences(a) => {
            let n = a.len().map_err(gerr)?;
            let mut out = Vec::with_capacity(n);
            for i in 0..n {
                out.push(
                    a.get(i)
                        .map_err(gerr)?
                        .ok_or_else(|| format!("{name}[{i}] is null"))?,
                );
            }
            Ok(out)
        }
        v => Err(format!(
            "{name}: an array expected, found {}",
            v.kind_name()
        )),
    }
}

fn int(o: &Object<'_>, name: &str) -> R<i64> {
    let v = o.get(name).map_err(gerr)?;
    v.as_i64()
        .ok_or_else(|| format!("{name}: an integer expected, found {}", v.kind_name()))
}

fn real(o: &Object<'_>, name: &str) -> R<f64> {
    o.f32(name).map(f64::from).map_err(gerr)
}

struct Edge {
    name: String,
    input: i64,
    output: i64,
}

struct Node<'f> {
    name: String,
    inputs: Vec<Edge>,
    kind: String,
    data: Option<Object<'f>>,
}

struct Dag<'f> {
    nodes: Vec<Node<'f>>,
    sources: Vec<i64>,
    masks: Vec<String>,
}

fn read_dag<'f>(dag: &Object<'f>) -> R<(Dag<'f>, usize)> {
    let root = usize::try_from(int(dag, "RootNodeIndex")?).map_err(|_| "negative root")?;
    let mut nodes = Vec::new();
    for n in items(dag, "Nodes")? {
        let mut inputs = Vec::new();
        for e in items(&n, "InputEdges")? {
            inputs.push(Edge {
                name: e.string("EdgeName").map_err(gerr)?.unwrap_or_default(),
                input: int(&e, "InputNodeIndex")?,
                output: int(&e, "ConnectedOutput")?,
            });
        }
        let data = n.reference("NodeData").map_err(gerr)?;
        let kind = data
            .as_ref()
            .and_then(|d| d.members().first())
            .and_then(|m| m.name.strip_prefix("TypeMarker_NodeData"))
            .unwrap_or("")
            .to_owned();
        nodes.push(Node {
            name: n.string("Name").map_err(gerr)?.unwrap_or_default(),
            inputs,
            kind,
            data,
        });
    }
    let mut sources = Vec::new();
    for s in items(dag, "Sources")? {
        sources.push(int(&s, "EventCode")?);
    }
    let mut masks = Vec::new();
    for m in items(dag, "TrackMasks")? {
        masks.push(m.string("BindingName").map_err(gerr)?.unwrap_or_default());
    }
    Ok((
        Dag {
            nodes,
            sources,
            masks,
        },
        root,
    ))
}

impl Dag<'_> {
    fn node(&self, i: i64) -> R<&Node<'_>> {
        usize::try_from(i)
            .ok()
            .and_then(|i| self.nodes.get(i))
            .ok_or_else(|| format!("node index {i} out of range"))
    }

    fn data<'a, 'g>(&self, n: &'a Node<'g>) -> R<&'a Object<'g>> {
        n.data
            .as_ref()
            .ok_or_else(|| format!("node {}: no data", n.name))
    }

    /// The node an input edge comes from; `None` when unconnected.
    fn input(&self, n: &Node<'_>, edge: &str) -> R<Option<i64>> {
        let e = n
            .inputs
            .iter()
            .find(|e| e.name == edge)
            .ok_or_else(|| format!("node {}: no input {edge:?}", n.name))?;
        if e.input < 0 {
            return Ok(None);
        }
        if e.output != 0 {
            return Err(format!(
                "node {}: input {edge:?} reads output {} of its source",
                n.name, e.output
            ));
        }
        Ok(Some(e.input))
    }

    fn pose(&self, i: Option<i64>, depth: u32) -> R<String> {
        let Some(i) = i else { return Ok("-".into()) };
        if depth > 64 {
            return Err("graph too deep".into());
        }
        let n = self.node(i)?;
        match n.kind.as_str() {
            "PoseAnimSource" => {
                let d = self.data(n)?;
                let e = items(d, "Edges")?
                    .into_iter()
                    .next()
                    .ok_or_else(|| format!("node {}: no source edge", n.name))?;
                // A node with no source (index -1) plays event code 0: nothing.
                let ec = match usize::try_from(int(&e, "SourceIndex")?) {
                    Err(_) => 0,
                    Ok(src) => *self
                        .sources
                        .get(src)
                        .ok_or_else(|| format!("node {}: source {src} out of range", n.name))?,
                };
                let mut s = format!(
                    "ec{ec}(loop={},clamp={},cont={},spd={},off={})",
                    int(&e, "LoopCount")?,
                    int(&e, "ClampedLoop")?,
                    int(&e, "ContinueOffset")?,
                    fmt_g(real(&e, "Speed")?),
                    fmt_g(real(&e, "Offset")?),
                );
                if let Some(first) = n.inputs.iter().find(|e| e.input >= 0) {
                    let name = first.name.clone();
                    s.push_str(&format!(
                        " IN[{}]",
                        self.scalar(self.input(n, &name)?, depth + 1)?
                    ));
                }
                Ok(s)
            }
            "Selection" => {
                let d = self.data(n)?;
                let sel = self.scalar(self.input(n, "Selector")?, depth + 1)?;
                let mut arms = Vec::new();
                for k in 0.. {
                    let edge = format!("Pose in ({k})");
                    if !n.inputs.iter().any(|e| e.name == edge) {
                        break;
                    }
                    arms.push(format!(
                        "{k}:{}",
                        self.pose(self.input(n, &edge)?, depth + 1)?
                    ));
                }
                Ok(format!(
                    "Select(sel={sel}, default={}){{{}}}",
                    int(d, "DefaultEdge")?,
                    arms.join("; ")
                ))
            }
            "Blend" => {
                let p = self.scalar(self.input(n, "Param")?, depth + 1)?;
                let from = self.pose(self.input(n, "From")?, depth + 1)?;
                let to = self.pose(self.input(n, "To")?, depth + 1)?;
                let mask = match self.input(n, "Mask")? {
                    None => "-".to_owned(),
                    Some(m) => self.mask(m)?,
                };
                Ok(format!("Blend(p={p}, from={from}, to={to}, mask={mask})"))
            }
            other => Err(format!("node {}: pose node of kind {other:?}", n.name)),
        }
    }

    fn mask(&self, i: i64) -> R<String> {
        let n = self.node(i)?;
        if n.kind != "Trackmask" {
            return Err(format!("node {}: mask node of kind {:?}", n.name, n.kind));
        }
        let d = self.data(n)?;
        let b = usize::try_from(int(d, "BindingIndex")?).map_err(|_| "negative binding")?;
        let binding = self
            .masks
            .get(b)
            .ok_or_else(|| format!("node {}: binding {b} out of range", n.name))?;
        Ok(format!(
            "Mask({binding} w={}->{})",
            fmt_g(real(d, "DefaultWeight")?),
            fmt_g(real(d, "TargetWeight")?)
        ))
    }

    fn scalar(&self, i: Option<i64>, depth: u32) -> R<String> {
        let Some(i) = i else { return Ok("-".into()) };
        if depth > 64 {
            return Err("graph too deep".into());
        }
        let n = self.node(i)?;
        let d = self.data(n)?;
        match n.kind.as_str() {
            "ScalarSource" => {
                let e = items(d, "Edges")?
                    .into_iter()
                    .next()
                    .ok_or_else(|| format!("node {}: no value", n.name))?;
                Ok(format!("const[{}]", fmt_const(real(&e, "Current")?)))
            }
            "BlockCurve" => {
                let first = items(d, "Blocks")?
                    .into_iter()
                    .next()
                    .ok_or_else(|| format!("node {}: no curve block", n.name))?;
                let t = int(&first, "BlockType")?;
                if t != 3 {
                    return Err(format!("node {}: curve block of type {t}", n.name));
                }
                Ok(format!(
                    "Curve3({})",
                    self.scalar(self.input(n, "Input")?, depth + 1)?
                ))
            }
            "ScalarCallback" => {
                let v = real(d, "CallbackValue")?;
                match int(d, "CallbackBindHint")? {
                    5 => Ok(format!("BlendTime({})", fmt_g(v))),
                    6 => Ok(format!("BlendEC({})", fmt_g(v))),
                    7 => Ok(format!("Path({})", fmt_g(v))),
                    h => Err(format!("node {}: scalar callback {h}", n.name)),
                }
            }
            other => Err(format!("node {}: scalar node of kind {other:?}", n.name)),
        }
    }
}

/// The expression of one `.dge` file: `Sub[<pose>]`.
pub fn decode_dge(bytes: &[u8]) -> R<String> {
    let file = GrannyFile::parse(bytes).map_err(gerr)?;
    let root = file.root().map_err(gerr)?;
    let dags = items(&root, "DAGs")?;
    let [dag] = dags.as_slice() else {
        return Err(format!("{} DAGs, one expected", dags.len()));
    };
    let (dag, root) = read_dag(dag)?;
    let top = dag
        .nodes
        .get(root)
        .ok_or_else(|| format!("root node {root} out of range"))?;
    if top.kind != "Subgraph" {
        return Err(format!("root node of kind {:?}", top.kind));
    }
    let input = top.inputs.first().ok_or("root node has no input")?.input;
    let input = (input >= 0).then_some(input);
    Ok(format!("Sub[{}]", dag.pose(input, 0)?))
}

/// The table of `graphs` (`(file name, bytes)`), sorted by name; the files that do not decode are
/// returned with the reason.
pub fn graphs_table(graphs: &[(String, Vec<u8>)]) -> (String, usize, Vec<(String, String)>) {
    let mut ok: BTreeMap<String, String> = BTreeMap::new();
    let mut failed = Vec::new();
    for (name, bytes) in graphs {
        match decode_dge(bytes) {
            Ok(expr) => {
                ok.insert(name.to_ascii_uppercase(), expr);
            }
            Err(why) => failed.push((name.clone(), why)),
        }
    }
    let mut text = String::from(TABLE_HEADER);
    for (name, expr) in &ok {
        text.push_str(name);
        text.push('\n');
        text.push_str(expr);
        text.push('\n');
    }
    (text, ok.len(), failed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_print_like_printf_g() {
        assert_eq!(fmt_g(1.0), "1");
        assert_eq!(fmt_g(0.0), "0");
        assert_eq!(fmt_g(0.15f32 as f64), "0.15");
        assert_eq!(fmt_g(1.0f32 as f64 / 3.0f32 as f64), "0.333333");
        assert_eq!(fmt_g(0.3333f32 as f64), "0.3333");
        assert_eq!(fmt_g(1420.0), "1420");
        assert_eq!(fmt_g(2.1137e-31f32 as f64), "2.1137e-31");
        assert_eq!(fmt_g(1234567.0), "1.23457e+06");
        assert_eq!(fmt_g(-0.5), "-0.5");
        assert_eq!(fmt_g(999999.5), "1e+06");
        assert_eq!(fmt_const(1.0), "1.0");
        assert_eq!(fmt_const(0.25), "0.25");
    }

    #[test]
    fn a_file_that_is_not_granny_is_reported() {
        let (text, n, failed) = graphs_table(&[("x.dge".into(), b"not a granny file".to_vec())]);
        assert_eq!(n, 0);
        assert_eq!(failed.len(), 1);
        assert!(text.starts_with('#'));
    }
}
