//! Builds Lua 5.1.5 as C++ with C linkage, plus the trampolines and the WASI shim on wasm.

use std::fs;
use std::path::PathBuf;

use build_support::{Lang, Toolchain};

/// Standalone programs, not library code.
const NOT_LIBRARY: &[&str] = &["lua.c", "luac.c", "print.c"];

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("set by Cargo"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("set by Cargo"));
    let lua_src = build_support::workspace_root().join("third_party/lua-5.1.5/src");
    // Public headers (lua.h, luaconf.h, ...) are vendored next to the sources; luaconf.h carries the
    // LEKMOD_LUA_INTEGER blocks shared with the gamecore build (third_party/lua-5.1.5/SOURCE.txt).
    let lua_include = lua_src.clone();
    let cpp = manifest.join("cpp");
    let toolchain = build_support::toolchain();

    build_support::rerun_if_dir_changed(&lua_src);
    build_support::rerun_if_dir_changed(&cpp);

    // Each .c is wrapped in a .cpp so standard headers precede `extern "C"`.
    let wrap_dir = out.join("lua-wrap");
    fs::create_dir_all(&wrap_dir).expect("create wrapper directory in OUT_DIR");
    let mut sources: Vec<PathBuf> = fs::read_dir(&lua_src)
        .unwrap_or_else(|e| panic!("no Lua sources in {}: {e}", lua_src.display()))
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "c"))
        .filter(|p| !NOT_LIBRARY.contains(&p.file_name().and_then(|n| n.to_str()).unwrap_or("")))
        .collect();
    sources.sort();
    assert!(!sources.is_empty(), "empty {}", lua_src.display());

    let mut lua = build_support::cc_build(Lang::Cxx17);
    lua.warnings(false)
        .include(&lua_src)
        .include(&lua_include)
        .include(&cpp)
        .define("LEKMOD_LUA_INTEGER", "int");
    if let Toolchain::WasiSdk { .. } = toolchain {
        // wasi-libc's clock() needs emulation.
        lua.define("_WASI_EMULATED_PROCESS_CLOCKS", None);
    }
    for src in &sources {
        let stem = src
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("Lua file name must be ASCII");
        let wrapper = wrap_dir.join(format!("{stem}.cpp"));
        let text = format!(
            "// Generated by lua-sys build.rs.\n#include \"lua_prelude.h\"\nextern \"C\" {{\n#include \"{}\"\n}}\n",
            src.display().to_string().replace('\\', "/")
        );
        write_if_changed(&wrapper, &text);
        lua.file(&wrapper);
    }
    lua.file(cpp.join("lua_sys.cpp"));
    lua.compile("lua51");

    if let Toolchain::WasiSdk { .. } = toolchain {
        build_support::cc_build(Lang::C)
            .file(cpp.join("wasi_shim.c"))
            .compile("lua_sys_wasi_shim");
        build_support::link_wasm_runtime();
    }

    println!("cargo:include={}", lua_include.display());
    println!("cargo:cpp_include={}", cpp.display());
}

fn write_if_changed(path: &std::path::Path, text: &str) {
    if fs::read_to_string(path).ok().as_deref() != Some(text) {
        fs::write(path, text).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
    }
}
