//! A 5x7 bitmap font for the HUD, drawn as filled rectangles into the draw list: the HUD of a mod has no font of the
//! game to use, and a few lines of text are all this example shows. Upper case, digits and the punctuation of
//! ASCII 0x20 to 0x5A; lower case is shown as upper case, anything else as `?`.
//!
//! Each glyph is five columns of seven bits (bit 0 is the top row), the classic table.

use mod_client::UiDrawList;
use mod_client::gpu::glam::Vec2;

