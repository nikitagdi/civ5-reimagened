/// Width of a character cell in glyph pixels (five columns and one of space).
const CELL: f32 = 6.0;
/// Height of a line in glyph pixels (seven rows and two of space).
const LINE: f32 = 9.0;

fn glyph(c: char) -> &'static [u8; 5] {
    let c = c.to_ascii_uppercase();
    let at = if (' '..='Z').contains(&c) {
        c as usize - 0x20
    } else {
        '?' as usize - 0x20
    };
    &GLYPHS[at]
}

/// Width of `text` in pixels at `scale` pixels per glyph pixel.
pub fn text_width(text: &str, scale: f32) -> f32 {
    text.chars().count() as f32 * CELL * scale
}

/// Height of a line in pixels.
pub fn line_height(scale: f32) -> f32 {
    LINE * scale
}

/// Draws `text` with its top left corner at `at`; `scale` is the size of one glyph pixel on the screen.
pub fn draw_text(list: &mut UiDrawList, at: Vec2, scale: f32, text: &str, color: [u8; 4]) {
    let mut x = at.x;
    for ch in text.chars() {
        for (col, bits) in glyph(ch).iter().enumerate() {
            for row in 0..7 {
                if bits >> row & 1 == 1 {
                    let min = Vec2::new(x + col as f32 * scale, at.y + row as f32 * scale);
                    list.add_filled_rect(min, min + Vec2::splat(scale), color);
                }
            }
        }
        x += CELL * scale;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_covers_the_range_and_a_known_glyph_is_right() {
        assert_eq!(GLYPHS.len(), 'Z' as usize - ' ' as usize + 1);
        // 'I' is a bar with serifs: the middle column is full.
        assert_eq!(glyph('i')[2], 0x7F);
        assert_eq!(glyph('~'), glyph('?'), "what the table lacks shows as ?");
    }

    #[test]
    fn text_draws_one_rect_a_lit_pixel_and_measures_by_cells() {
        let mut list = UiDrawList::new();
        draw_text(&mut list, Vec2::ZERO, 2.0, "I", [255; 4]);
        let lit: u32 = glyph('I').iter().map(|b| b.count_ones()).sum();
        assert_eq!(list.vertices().len(), lit as usize * 4);
        assert_eq!(text_width("HELLO", 2.0), 60.0);
        assert_eq!(line_height(2.0), 18.0);
    }
}
